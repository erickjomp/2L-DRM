MODULE toml_config
    ! Reads the configuration file (TOML) given with --config and converts it into a flat INI
    ! file for FLAP's set_config, so command line flags still override its values.
    ! TOML keys are the long option names of run2LDRM --help (without "--");
    ! [sections] are only for grouping and are ignored.

    implicit none
    private
    public :: config_argument, toml_to_ini, temporary_ini_name, delete_file

contains

    ! value of --config / -c in the actual command line, '' if not passed
    function config_argument() result(path)
        character(len=:), allocatable :: path
        character(len=:), allocatable :: arg
        integer                       :: i, n

        path = ''
        n = command_argument_count()
        do i = 1, n
            arg = command_argument(i)
            if ((arg == '--config' .or. arg == '-c') .and. i < n) then
                path = command_argument(i + 1)
                return
            else if (index(arg, '--config=') == 1) then
                path = arg(len('--config=') + 1:)
                return
            end if
        end do
    end function

    function command_argument(i) result(arg)
        integer, intent(in)           :: i
        character(len=:), allocatable :: arg
        integer                       :: length

        call get_command_argument(i, length=length)
        allocate(character(len=length) :: arg)
        call get_command_argument(i, arg)
    end function

    ! writes every key = value of the TOML file (any nesting) into ini_file
    subroutine toml_to_ini(toml_file, ini_file)
        use tomlf, only : toml_table, toml_error, toml_load
        character(len=*), intent(in)  :: toml_file, ini_file
        type(toml_table), allocatable :: table
        type(toml_error), allocatable :: error
        integer                       :: unit

        call toml_load(table, toml_file, error=error)
        if (allocated(error)) then
            write(*,'(A)') "Error reading configuration file '" // trim(toml_file) // "':"
            write(*,'(A)') error%message
            error stop
        end if

        open(newunit=unit, file=ini_file, status='replace', action='write')
        write(unit,'(A)') '# generated by run2LDRM from ' // trim(toml_file)
        call write_table(table, unit, toml_file)
        close(unit)
    end subroutine

    recursive subroutine write_table(table, unit, toml_file)
        use tomlf, only : toml_table, toml_keyval, toml_key, toml_datetime, get_value, to_string
        use tomlf_constants, only : toml_type
        use, intrinsic :: iso_fortran_env, only : int64, real64
        type(toml_table), intent(inout) :: table
        integer, intent(in)             :: unit
        character(len=*), intent(in)    :: toml_file
        type(toml_key), allocatable     :: keys(:)
        type(toml_table), pointer       :: child
        type(toml_keyval), pointer      :: keyval
        character(len=:), allocatable   :: key, value
        character(len=64)               :: buffer
        integer(int64)                  :: int_value
        real(real64)                    :: real_value
        logical                         :: bool_value
        type(toml_datetime)             :: date_value
        integer                         :: i

        call table%get_keys(keys)
        do i = 1, size(keys)
            key = keys(i)%key
            call get_value(table, key, child, requested=.false.)
            if (associated(child)) then   ! [section]
                call write_table(child, unit, toml_file)
                cycle
            end if

            call get_value(table, key, keyval)
            if (.not. associated(keyval)) then
                write(*,'(A)') "Configuration file '" // trim(toml_file) // "': '" // key // &
                               "' must be a single value, not an array"
                error stop
            end if

            select case (keyval%get_type())
            case (toml_type%string)
                call get_value(table, key, value)
            case (toml_type%int)
                call get_value(table, key, int_value)
                write(buffer,'(I0)') int_value
                value = trim(buffer)
            case (toml_type%float)
                call get_value(table, key, real_value)
                write(buffer,'(G0)') real_value
                value = trim(adjustl(buffer))
            case (toml_type%boolean)
                call get_value(table, key, bool_value)
                value = merge('.true. ', '.false.', bool_value)
                value = trim(value)
            case (toml_type%datetime)   ! 2018-05-01T00:00:00 -> 2018-05-01_00:00:00 (CLI format)
                call get_value(table, key, date_value)
                value = to_string(date_value)
                if (len(value) > 10) value(11:11) = '_'
            end select

            if (index(value, '"') > 0) then
                write(*,'(A)') "Configuration file '" // trim(toml_file) // "': value of '" // key // &
                               "' cannot contain '""'"
                error stop
            end if
            write(unit,'(A)') key // ' = "' // value // '"'
        end do
    end subroutine

    ! unique name, so runs started at the same time do not share the file
    function temporary_ini_name() result(path)
        character(len=:), allocatable :: path
        character(len=512)            :: tmpdir
        character(len=32)             :: suffix
        integer                       :: status, count
        real                          :: random

        call get_environment_variable('TMPDIR', tmpdir, status=status)
        if (status /= 0 .or. len_trim(tmpdir) == 0) tmpdir = '.'
        call system_clock(count)
        call random_number(random)
        write(suffix,'(I0,"_",I0)') count, int(random * 1.0e6)
        path = trim(tmpdir) // '/run2LDRM_config_' // trim(suffix) // '.ini'
    end function

    subroutine delete_file(path)
        character(len=*), intent(in) :: path
        integer                      :: unit, ios

        open(newunit=unit, file=path, status='old', iostat=ios)
        if (ios == 0) close(unit, status='delete')
    end subroutine

END MODULE toml_config
